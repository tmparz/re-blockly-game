export function t(name, params = {}) {
  const text = UI[lang][name] ?? UI.en[name] ?? name;
  return text.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? ""));
}

export const L = (en, zh) => (lang === "zh" ? zh : en);
